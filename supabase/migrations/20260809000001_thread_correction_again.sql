-- 갈래 교정을 되살린다. 20260808000002 로 버렸던 것을 다시 넣는다.
--
-- 어제 버릴 때 이유가 둘이었다. **하나는 측정이 뒤집혔고, 하나는 답을 만들었다.**
--
-- ── 뒤집힌 이유: "그 연쇄는 다른 것이 풀었다" ──
--
-- 어제는 재구축 4회차에서 모델이 교정 없이 스스로 갈랐다는 관찰로 버렸다.
-- 후보 목록을 넓힌 것(어휘 tsquery + 상한 5→8)이 풀었다고 봤다.
--
-- 오늘 통제된 시험대로 재보니 **연쇄는 안 풀렸다.**
-- 함정을 심은 세션 40개를 3회 돌린 결과(docs/HANDOFF-attach.md):
--
--   쌍 F1 54.3%  (정밀 43 / 재현 74)
--   가장 큰 갈래는 언제나 가장 먼저 만들어진 갈래였다
--   24건 [베타:13 알파:8 컨퍼런스A:1 알파-리포트:1 감마문서:1] "베타 스토어 배포"
--
-- 어제 본 것은 사례 하나였다. 그리고 프롬프트로 고치려는 시도는 여섯 개가
-- 전부 잡음 안에서 죽었다 — 왜인지는 오라클 시험이 답했다. 갈래 목록만
-- 올바르게 주면 **프롬프트를 하나도 안 고쳐도 89.2%** 다. 판단력에 남은
-- 여지가 11% 뿐이고, 나머지 30pt 는 목록이 이미 오염된 채 들어오는 데서 온다.
-- 모델이 규칙을 어기는 게 아니라 어질러진 상태를 정확히 읽는 것이다.
--
-- 사람이 고치면 F1 이 54 → 60~88 로 올라간다. 40세션에 5~15번, 하루 한두 번꼴.
--
-- ── 남은 이유: 옮기기가 만드는 미정의 상태 다섯 ──
--
-- 이건 정당한 지적이었고 그대로 살아 있다. 경험이 갈래를 **떠나는** 상태는
-- 엔진 경로에 없어서 다음이 전부 미정의였다:
--   ① 원래 기억의 근거가 0건이 되면?
--   ② deepened(6건)가 5건으로 줄면 취소되나?
--   ③ 원래 갈래가 비면 그 기억은 삭제인가?
--   ④ 옮긴 경험이 목적지에서 기억 조건을 못 넘으면?
--   ⑤ memory_score 를 다시 재나, 저장값을 쓰나?
--
-- 규칙 다섯 개가 아니라 **원칙 하나**로 답한다. 이미 이 스키마에 적혀 있다:
--
--   "1월에 처음 써본 게 있었고(new_skill) 3월에 6건째가 됐다면(deepened)
--    둘 다 사실이다"  — memories.triggers 주석
--
--   ▶ 기억은 발화한 사실이다. 옮기기는 갈래 배정만 바꾸고
--     기억 평가를 다시 돌리지 않는다.
--
--   ① 기억은 남는다. experience_ids 에서만 빼고 needs_resummary 를 세운다.
--      배열은 발화 근거가 아니라 **요약 재료**라, 남의 갈래 경험이 섞이면
--      밤 요약이 틀린다. 발화 사실 자체는 안 건드린다.
--   ② 취소하지 않는다. 그때는 실제로 6건이었다. triggers 는 append-only 다.
--   ③ 기억이 가리키는 갈래는 비어도 남긴다 — memories.thread_id 의 FK 가
--      onDelete 없이 걸려 있어 DB 가 이미 그렇게 강제한다. 기억이 없는 빈
--      갈래만 지운다.
--   ④ 아무 일도 일어나지 않는다. 옮기기는 과거 오배정의 교정이지 새 사건이
--      아니다. 그 갈래의 다음 실제 세션이 평가한다.
--   ⑤ 저장값을 쓴다. 다시 재는 것은 발화 사실을 뒤집는 일이다.
--
-- ── thread 만 다른 점 (20260808000001 에서 그대로 가져온다) ──
--
-- 나머지 세 필드는 라벨이라 읽을 때 겹치면 되지만, 갈래는 관계(FK)다.
-- 후보 목록·"최근:" 줄·경험 개수가 전부 thread_id 조인에서 나오므로 겹쳐
-- 읽기로만 처리하면 조인 지점 하나만 빠뜨려도 교정이 아무 데도 안 쓰이는
-- 라벨 더미가 된다. 그래서 experiences.thread_id 를 실제로 옮긴다.
-- (모델 출력, 사람 정답) 쌍은 corrections 행에 남으므로 append-only 의
-- **이유**는 지켜진다 — model_value 에 옮기기 전 갈래 제목을 박제한다.
--
-- human_value 는 갈래 **제목**이다. id 가 아닌 이유: 재구축이 threads 를
-- 통째로 다시 만들어 uuid 가 매번 새로 발급된다. 제목으로 두면 재구축 때
-- 그 제목의 갈래를 찾고, 없으면 만들어서 다시 잇는다 — 사람이 "이건 KT
-- Cloud 갈래다"라고 말한 것은 그 갈래가 있어야 한다는 선언이기도 하다.
-- ============================================================

alter table corrections drop constraint if exists corrections_field_check;
alter table corrections add constraint corrections_field_check
  check (field in ('outcome', 'category', 'is_first_time', 'thread'));

alter table questions drop constraint if exists questions_field_check;
alter table questions add constraint questions_field_check
  check (field in ('outcome', 'category', 'is_first_time', 'thread'));

-- 지도에서 직접 고친 것. diary(일기 화면)·ask(캐릭터 질문)와 구분한다 —
-- 갈래 교정은 캐릭터가 물어서가 아니라 사람이 지도를 보다가 하는 일이라
-- 출처가 다르고, 나중에 "무엇을 계기로 고쳤나"를 갈라 볼 수 있어야 한다.
alter table corrections drop constraint if exists corrections_source_check;
alter table corrections add constraint corrections_source_check
  check (source in ('diary', 'ask', 'map'));
