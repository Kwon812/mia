-- ============================================================
-- 승인된 절차에 사람이 읽는 설명을 붙인다.
--
-- steps 는 기계가 읽는 명세다 — 셀렉터와 순서. 사람도 에이전트도 그걸로는
-- "이게 무슨 일인지"를 모른다. skill_md 가 그 자리를 메운다.
--
-- 둘 다 두는 이유: 실행은 steps 로 하고(빠르고 공짜다), 화면이 바뀌어
-- 셀렉터가 안 맞으면 skill_md 로 떨어진다(에이전트가 읽고 새 자리를 찾는다).
-- 하나만 두면 그 복구 경로가 없다.
--
-- postcondition 은 "성공했다는 걸 무엇으로 아나"다. 이게 있어야 나중에
-- 리플레이·검증자를 붙일 수 있고, 없으면 그때 전부 다시 써야 한다.
-- ============================================================

alter table procedures add column if not exists skill_md text;
alter table procedures add column if not exists postcondition text;
