-- ============================================================
-- users.auth_id — 계정에 구글 신원을 붙인다.
--
-- devices 가 키를 기기로 낮췄으니(20260827000001), 이제 계정 쪽에 사람이
-- 다시 찾아올 수 있는 손잡이가 필요하다. 그게 이 컬럼이다.
--
-- NULL 이 정상 상태다. Day 0 는 확장 설치 → 익명 키 → 바로 시작이고,
-- 구글 연결은 사흘쯤 키운 뒤 "이 브라우저를 벗어나면 다 잊어버려" 하는
-- 시점에 사용자가 자발적으로 누르는 것이다. 첫날 가입 폼을 들이밀면
-- 이탈한다는 게 계획서의 판단이고, 그래서 NOT NULL 이 아니다.
--
-- **on delete set null 인 것이 중요하다.** cascade 로 두면 구글 계정을
-- 지우는 순간 캐릭터가 통째로 사라진다. 신원은 문일 뿐이고 집이 아니다 —
-- 문을 떼어내도 집은 남아야 한다. 그때 그 계정은 다시 기기 키로만 열리는
-- 상태로 돌아갈 뿐이다.
-- ============================================================

alter table users
  add column if not exists auth_id uuid unique references auth.users(id) on delete set null;

-- 언제 연결했나. 캐릭터의 서사에 쓸 값이라 남긴다("우리가 이어진 날").
alter table users
  add column if not exists linked_at timestamptz;
